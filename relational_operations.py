# Relational Operators

first_number = int(input("Enter first number: "))
second_number = int(input("Enter second number: "))

greater= first_number > second_number
less = first_number < second_number
equal= first_number == second_number
not_equal = first_number != second_number
greater_equal = first_number >= second_number
less_equal = first_number <= second_number

print("Greater than =", greater)
print("Less than =", less)
print("Equal to =", equal)
print("Not equal to =", not_equal)
print("Greater than or equal =", greater_equal)
print("Less than or equal =", less_equal)