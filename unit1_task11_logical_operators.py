# Logical Operators

first_value = bool(int(input("Enter first value (1 or 0): ")))
second_value = bool(int(input("Enter second value (1 or 0): ")))

and_result = first_value and second_value
or_result = first_value or second_value
not_result = not first_value

print("AND =", and_result)
print("OR =", or_result)
print("NOT First Value =", not_result)
