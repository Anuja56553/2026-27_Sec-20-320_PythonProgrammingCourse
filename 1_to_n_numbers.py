#for loop
number_limit = int(input("Enter the limit: "))

for current_number in range(1, number_limit + 1):
    print(current_number)
#while loop
number_limit = int(input("Enter the limit: "))

current_number = 1

while current_number <= number_limit:
    print(current_number)
    current_number = current_number + 1